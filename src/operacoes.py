# Módulo de operações básicas matemáticas

# Somar()
def somar(a,b):
    return (a+b)

# Subtrair()
def subtrair(a,b):
    return (a-b)

# Multiplicar()
def multiplicar(a,b):
    return (a*b)

# Dividir()
def dividir(a,b):
    return (a/b)
